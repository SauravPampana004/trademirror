import { Trade, TradeMetrics, Insight } from '../types/trade';

/**
 * Downloads a CSV string as a file in the browser
 */
export function downloadCsvFile(content: string, filename: string): void {
  const blob = new Blob([content], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Exports a set of trades to CSV
 */
export function exportTradesToCsv(trades: Trade[], filename = 'trademirror-trades.csv'): void {
  const headers = ['TradeID', 'Date', 'Symbol', 'Side', 'Quantity', 'EntryPrice', 'ExitPrice', 'RealizedPnL', 'Fees', 'Currency', 'Notes'];
  const rows = trades.map(t => [
    t.id,
    t.date,
    t.symbol,
    t.side,
    t.quantity,
    t.entryPrice.toFixed(2),
    t.exitPrice.toFixed(2),
    t.pnl.toFixed(2),
    t.fees.toFixed(2),
    t.currency,
    `"${(t.notes || '').replace(/"/g, '""')}"`
  ].join(','));

  const csvContent = [headers.join(','), ...rows].join('\n');
  downloadCsvFile(csvContent, filename);
}

/**
 * Generates an executive Markdown report suitable for PM review or clipboard copy
 */
export function generateMarkdownReport(
  datasetName: string,
  metrics: TradeMetrics,
  insights: Insight[],
  trades: Trade[]
): string {
  const timestamp = new Date().toLocaleString();
  const profitFactorStr = metrics.profitFactor !== null ? metrics.profitFactor.toFixed(2) : (metrics.grossProfit > 0 ? 'Infinite (0 Losses)' : '0.00');

  let md = `# TradeMirror Executive Trade Performance Report\n`;
  md += `**Dataset:** ${datasetName} | **Generated:** ${timestamp}\n\n`;

  md += `## 1. Executive Performance Summary\n`;
  md += `| Metric | Value | Benchmark / Note |\n`;
  md += `| :--- | :--- | :--- |\n`;
  md += `| **Net Realized P&L** | **$${metrics.netPnl.toFixed(2)}** | Total realized return |\n`;
  md += `| **Total Trades** | ${metrics.totalTrades} | ${metrics.winningTrades} Wins / ${metrics.losingTrades} Losses (${metrics.breakevenTrades} BE) |\n`;
  md += `| **Win Rate** | ${metrics.winRate.toFixed(1)}% | Win frequency percentage |\n`;
  md += `| **Profit Factor** | ${profitFactorStr} | Gross Wins ($${metrics.grossProfit.toFixed(2)}) / Gross Losses ($${metrics.grossLoss.toFixed(2)}) |\n`;
  md += `| **Avg Winning Trade** | +$${metrics.avgWinningTrade.toFixed(2)} | Average upside capture |\n`;
  md += `| **Avg Losing Trade** | -$${Math.abs(metrics.avgLosingTrade).toFixed(2)} | Average downside drag |\n`;
  md += `| **Payoff Ratio** | ${metrics.payoffRatio !== null ? metrics.payoffRatio.toFixed(2) + ':1' : 'N/A'} | Win size to loss size ratio |\n`;
  md += `| **Total Fees Paid** | $${metrics.totalFees.toFixed(2)} | Brokerage & exchange friction |\n`;
  md += `| **Max Drawdown** | -$${metrics.maxDrawdown.toFixed(2)} (${metrics.maxDrawdownPct.toFixed(1)}%) | Peak to valley retracement |\n\n`;

  md += `## 2. Evidence-Backed Trading Patterns (${insights.length} Identified)\n\n`;

  insights.forEach((ins, idx) => {
    md += `### ${idx + 1}. ${ins.title}\n`;
    md += `- **Pattern Category:** ${ins.tag}\n`;
    md += `- **Finding:** ${ins.summary}\n`;
    md += `- **Supporting Evidence:**\n`;
    ins.supportingNumbers.forEach(s => {
      md += `  - **${s.label}:** ${s.value} (${s.sublabel || ''})\n`;
    });
    md += `- **Sample Size:** ${ins.sampleSize} trades (${ins.sampleSizePct}% of dataset)\n`;
    md += `- **Statistical Limitations:** ${ins.limitations}\n`;
    md += `- **Suggested Action:** ${ins.suggestedAction}\n\n`;
  });

  md += `## 3. Trade Audit Log Summary\n`;
  md += `Total trades logged: ${trades.length}. Earliest trade: ${trades[0]?.date || 'N/A'}, Latest trade: ${trades[trades.length - 1]?.date || 'N/A'}.\n\n`;
  md += `---\n*Generated by TradeMirror for Nubra Product Management Intern Assessment.*`;

  return md;
}
